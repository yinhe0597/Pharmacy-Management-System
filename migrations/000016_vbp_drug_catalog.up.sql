-- 数据来源: 国家组织药品联合采购办公室各批次中选结果公告, 共 392 条（去重）
-- 用途: 药品名称模糊搜索/自动补全, 后续入库时再精确填列规格/厂家/价格

-- 国家集采药品参考目录表
CREATE TABLE vbp_drug_catalog (
    id              BIGSERIAL PRIMARY KEY,
    generic_name    VARCHAR(150) NOT NULL,
    dosage_form     VARCHAR(40)  NOT NULL,
    dosage_category VARCHAR(30),
    vbp_batch       SMALLINT     NOT NULL,
    py_code         VARCHAR(50),
    is_common       BOOLEAN NOT NULL DEFAULT FALSE,
    status          SMALLINT NOT NULL DEFAULT 1,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_vbp_name ON vbp_drug_catalog (generic_name);
CREATE INDEX idx_vbp_py ON vbp_drug_catalog (py_code);
CREATE INDEX idx_vbp_batch ON vbp_drug_catalog (vbp_batch);
CREATE INDEX idx_vbp_form ON vbp_drug_catalog (dosage_form);

